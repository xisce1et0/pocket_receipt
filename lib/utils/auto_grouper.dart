String _toCyrillicHomoglyphs(String input) {
  const map = <String, String>{
    'a': 'а',
    'b': 'в',
    'c': 'с',
    'e': 'е',
    'h': 'н',
    'k': 'к',
    'm': 'м',
    'o': 'о',
    'p': 'р',
    't': 'т',
    'x': 'х',
    'y': 'у',
  };
  final lower = normalizeProductName(input);
  final sb = StringBuffer();
  for (final code in lower.runes) {
    final ch = String.fromCharCode(code);
    sb.write(map[ch] ?? ch);
  }
  return sb.toString();
}

class _GroupRule {
  final String group;
  final List<RegExp> patterns;

  const _GroupRule(this.group, this.patterns);
}

RegExp _wordPrefix(String stem, {bool exactWord = false}) {
  final escaped = RegExp.escape(stem);
  final tail = exactWord ? r'(?=$|[^\p{L}])' : '';
  return RegExp(
    '(?:^|[^\\p{L}])$escaped$tail',
    caseSensitive: false,
    unicode: true,
  );
}

